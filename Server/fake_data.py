    for 索引, 模板 in enumerate(商品模板):
        地区 = 地区池[索引 % len(地区池)]
        降价 = 索引 % 4 == 1
        商品ID = 100000 + 索引 * 2
        列表.append({
            'id': str(商品ID),
            '标题': 模板['标题'],
            '价格': 模板['价格'],
            '地区': 地区,
            '图片': 生成占位图(模板['关键词']),
            '链接': f'https://www.goofish.com/item?id={商品ID}',
            '所属关键词': 模板['关键词'],
            '首次发现': 偏移时间(-24 * (8 + 索引 % 20)),
            '最近发现': 偏移时间(-(索引 % 6)) if 索引 % 4 == 3 else 偏移时间(-24 * (1 + 索引 % 8)),
            '降价': 降价,
            '收藏': 索引 % 5 == 0,
        })
        历史价格 = 模板['价格'] + 30 + (索引 % 5) * 20
        列表.append({
            'id': str(商品ID + 1),
            '标题': f"{模板['标题']}（配件齐全）",
            '价格': 模板['价格'] - 40 if 降价 else 历史价格,
            '地区': 地区池[(索引 + 3) % len(地区池)],
            '图片': 生成占位图(模板['关键词']),
            '链接': f'https://www.goofish.com/item?id={商品ID + 1}',
            '所属关键词': 模板['关键词'],
            '首次发现': 偏移时间(-24 * (25 + 索引 % 15)),
            '最近发现': 偏移时间(-(索引 % 8) - 1) if 降价 else 偏移时间(-24 * (3 + 索引 % 10)),
            '降价': 降价,
            '收藏': False,
        })
    return 列表


