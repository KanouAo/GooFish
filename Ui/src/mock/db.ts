/** 将日期格式化为 YYYY-MM-DD HH:mm:ss */
export function 格式化时间(日期: Date): string {
  const 补齐 = (值: number) => String(值).padStart(2, '0')
  return (
    `${日期.getFullYear()}-${补齐(日期.getMonth() + 1)}-${补齐(日期.getDate())} ` +
    `${补齐(日期.getHours())}:${补齐(日期.getMinutes())}:${补齐(日期.getSeconds())}`
  )
}

/** 相对当前时间偏移指定小时（可为小数、负数） */
export function 偏移时间(小时: number): string {
  return 格式化时间(new Date(Date.now() + 小时 * 3600 * 1000))
}

/** 生成内联 SVG 占位图（离线可用，不依赖外部图床） */
export function 生成占位图(文字: string): string {
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" width="160" height="160">` +
    `<rect width="100%" height="100%" fill="#fff2e8"/>` +
    `<text x="50%" y="46%" dominant-baseline="middle" text-anchor="middle" ` +
    `font-size="18" fill="#fa541c" font-family="sans-serif">${文字}</text>` +
    `<text x="50%" y="64%" dominant-baseline="middle" text-anchor="middle" ` +
    `font-size="10" fill="#fa8c16" font-family="sans-serif">闲鱼商品图占位</text></svg>`
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`
}

