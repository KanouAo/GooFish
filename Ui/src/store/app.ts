//  全局应用状态（Zustand）：调度状态 + SSE 事件刷新计数器 + 爬取实时进度
import { create } from 'zustand'
import { 获取调度状态 } from '@/api/scheduler'
import type { 调度状态类型, 爬取进度类型 } from '@/types/biz'

interface 应用状态类型 {
  /** 调度器状态（侧边菜单与调度页共用） */
  调度状态: 调度状态类型 | null
  /** 拉取最新调度状态 */
  加载调度状态: () => Promise<void>
  /** 直接设置调度状态（操作后本地更新，避免重复请求） */
  设置调度状态: (状态: 调度状态类型) => void
  //  SSE 事件刷新计数器：每次收到事件自增，页面监听计数器变化触发重新拉取
  上新事件计数: number
  降价事件计数: number
  触发上新事件: () => void
  触发降价事件: () => void
  /** 当前正在爬取的任务实时进度（SSE「进度」事件驱动；进行中组件才显示） */
  爬取进度: 爬取进度类型 | null
  设置爬取进度: (进度: 爬取进度类型) => void
}

export const use应用Store = create<应用状态类型>((set) => ({
  调度状态: null,
  加载调度状态: async () => {
    const 状态 = await 获取调度状态()
    set({ 调度状态: 状态 })
  },
  设置调度状态: (状态) => set({ 调度状态: 状态 }),
  上新事件计数: 0,
  降价事件计数: 0,
  触发上新事件: () => set((s) => ({ 上新事件计数: s.上新事件计数 + 1 })),
  触发降价事件: () => set((s) => ({ 降价事件计数: s.降价事件计数 + 1 })),
  爬取进度: null,
  设置爬取进度: (进度) => set({ 爬取进度: 进度 }),
}))
